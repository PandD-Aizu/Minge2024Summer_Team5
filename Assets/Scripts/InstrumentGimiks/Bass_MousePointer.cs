using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Bass_MousePointer : MonoBehaviour
{
    public float rotationSpeed = 4f;  // ???]???x
    private GameObject rotatingObject = null;  // ???]?????I?u?W?F?N?g
    private Quaternion targetRotation;  // ?^?[?Q?b?g?????]?p?x
    private bool isRotating = false;  // ???]?????????????????????t???O
    public float stopThreshold = 0.5f; // ???]?????????????p?x?????l
    public int GearClicked = 0;/*Stage5-3???M?A???N???b?N????????????*/

    [SerializeField]
    private GameObject dragObject = null;  // ?h???b?O?????I?u?W?F?N?g
    [SerializeField]
    private Vector3 offset;  // ?}?E?X???I?u?W?F?N?g???I?t?Z?b?g

    [SerializeField] private AudioSource Bassaudio;
    [SerializeField] private AudioClip BassSound;

    private void Start()
    {
        Bassaudio = GetComponent<AudioSource>();
    }

    private void Update()
    {
        // ?I?u?W?F?N?g?????]??????????
        if (isRotating && rotatingObject != null)
        {
            // ?????????]???^?[?Q?b?g???]???X???[?Y????????????
            rotatingObject.transform.rotation = Quaternion.Slerp(
                rotatingObject.transform.rotation,
                targetRotation,
                Time.deltaTime * rotationSpeed
            );

            // ???]???????????????p?x?????`?F?b?N
            if (Quaternion.Angle(rotatingObject.transform.rotation, targetRotation) < stopThreshold)
            {
                // ???I?I?????W?p?x?????B??????
                rotatingObject.transform.rotation = targetRotation;
                rotatingObject = null; // ???]?????????I?u?W?F?N?g???Q?????N???A
                isRotating = false;    // ???]?????????????t???O???I?t??????
            }
        }
        // ?h???b?O?????I?u?W?F?N?g?????????????}?E?X?????u?????]??????
        if (dragObject != null)
        {
            Ray ray = Camera.main.ScreenPointToRay(Input.mousePosition);
            Plane plane = new Plane(Vector3.forward, Vector3.zero);  //z???????????????????`
            float distance;

            if (plane.Raycast(ray, out distance))
            {
                Vector3 targetPosition = ray.GetPoint(distance) + offset;  // ?I?t?Z?b?g?????????????u??????
                dragObject.transform.position = targetPosition;
            }

            // ?}?E?X?????{?^?????????????h???b?O?I??
            if (Input.GetMouseButtonUp(0))
            {
                dragObject = null;  // ?h???b?O?????I?u?W?F?N?g???Q?????N???A
            }
        }
        else
        {
            // �N���b�N�𔻒�
            if (Input.GetMouseButtonDown(0) && Time.timeScale == 1) // ���N���b�N�𔻒�
            {
                Bassaudio.PlayOneShot(BassSound);
                // ???C???J?????????}?E?X?J?[?\???????????u????Ray????????
                Ray ray = Camera.main.ScreenPointToRay(Input.mousePosition);
                RaycastHit hit;

                if (Physics.Raycast(ray, out hit, Mathf.Infinity))
                {
                    // Ray???????????I?u?W?F?N?g???????O???\??
                    Debug.Log(hit.collider.gameObject.name);

                    // "LaserReflector"?^?O???????I?u?W?F?N?g??????????????
                    if (!isRotating && hit.collider.gameObject.tag == "LaserReflector")
                    {
                        // ???]???????I?u?W?F?N?g???^?[?Q?b?g?????]?p?x??????
                        rotatingObject = hit.collider.gameObject;

                        // ???]???????I?u?W?F?N?g???p?x????????????????45?x?P??????????
                        rotatingObject.transform.rotation = Quaternion.Euler(
                            Mathf.Round(rotatingObject.transform.rotation.eulerAngles.x / 45) * 45,
                            Mathf.Round(rotatingObject.transform.rotation.eulerAngles.y / 45) * 45,
                            Mathf.Round(rotatingObject.transform.rotation.eulerAngles.z / 45) * 45
                        );

                        // ?^?[?Q?b?g?????]?p?x???????iZ????90?x???]?j
                        targetRotation = rotatingObject.transform.rotation * Quaternion.Euler(0, 0, 90);
                        isRotating = true; // ???]???t???O???I????????
                    }

                    // "Dragable"?^?O???????I?u?W?F?N?g???????????????A?h???b?O???????J?n
                    if (hit.collider.gameObject.tag == "Dragable")
                    {
                        Debug.Log("hit Dragable");
                        dragObject = hit.collider.gameObject;
                        offset.x = dragObject.transform.position.x - hit.point.x;
                        offset.y = dragObject.transform.position.y - hit.point.y;// ?I?t?Z?b?g???v?Z
                    }

                    //"Boss" ?^?O???????I?u?W?F?N?g?????????A?????????{?X??isAttacking??false???????????t?F?[?Y???i?s?????B
                    if (hit.collider.gameObject.tag == "Boss") {
                        if (hit.collider.gameObject.GetComponent<BossEnemy>().isAttacking == false) { 
                            hit.collider.gameObject.GetComponent<BossEnemy>().TakeDamage();
                        }
                    }

                    /*"GearClickable"???^?O???????I?u?W?F?N?g?????????????A?M?A?????????t???O????????*/
                    if (hit.collider.gameObject.tag == "GearClickable")
                    {
                        GearClicked = 1;
                    }
                    
                }
            }
        }
    }
}
