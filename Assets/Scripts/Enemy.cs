using UnityEngine;
using System.Collections;

public class Enemy : MonoBehaviour
{
    public float moveDistance = 10f;  // ?E???i??????
    public float moveSpeed = 2f;     // ???????x
    public float waitTime = 1f;      // ?????????????????@????

    private Vector3 startPoint;      // ???????u
    public bool movingRight = true; // ???????????????itrue = ?E, false = ???j

    void Start()
    {
        // ?G?????????u???L?^
        startPoint = transform.position;

        // ?R???[?`?????J?n
        StartCoroutine(Patrol());
    }

    // ?G?????E???????????R???[?`??
    IEnumerator Patrol()
    {
        while (true)
        {
            // ???I?n???v?Z
            Vector3 targetPoint = movingRight ? startPoint + Vector3.right * moveDistance : startPoint - Vector3.right * moveDistance;

            // ???I?n????????????
            while (Vector3.Distance(transform.position, targetPoint) > 0.1f)
            {
                transform.position = Vector3.MoveTowards(transform.position, targetPoint, moveSpeed * Time.deltaTime);
                yield return null; // ?t???[?????????????????@
            }

            // ???????????A???????@
            yield return new WaitForSeconds(waitTime);

            // ?????????????]
            movingRight = !movingRight;
        }
    }
}